    // 3. Métodos del Oráculo
    checkOracle: function (odds, question) {
        var currentOdds = odds || "even";
        var currentQuestion = question || "Pregunta al Oráculo";

        var d1 = this.d(20);
        var d2 = this.d(20);
        var finalRoll = d1;
        var rollDetails = "d20: [" + d1 + "]";

        if (currentOdds === "unlikely") {
            finalRoll = Math.min(d1, d2);
            rollDetails = "Desventaja (Poco probable): [" + d1 + ", " + d2 + "] -> " + finalRoll;
        } else if (currentOdds === "likely") {
            finalRoll = Math.max(d1, d2);
            rollDetails = "Ventaja (Probable): [" + d1 + ", " + d2 + "] -> " + finalRoll;
        } else {
            rollDetails = "Tirada Normal (50/50): [" + d1 + "]";
        }

        var answer = "";
        var isTwist = false;
        var isCritical = finalRoll === 1 || finalRoll === 20;
        var isOdd = finalRoll % 2 !== 0 && finalRoll !== 1;

        if (finalRoll === 10) {
            answer = "¡GIRO INESPERADO!";
        } else if (finalRoll === 20) {
            answer = "¡SÍ, Y ADEMÁS...!";
        } else if (finalRoll === 1) {
            answer = "¡NO, Y ADEMÁS...!";
        } else if (finalRoll >= 11) {
            answer = isOdd ? "SÍ, PERO..." : "SÍ";
        } else {
            answer = isOdd ? "NO, PERO..." : "NO";
        }
        var nuance = "";
        if (isCritical) {
            if (finalRoll === 20) {
                nuance = "¡Éxito Crítico! SÍ, y además de la forma más favorable posible.";
            } else {
                nuance = "¡Pifia Crítica! NO, y de la forma más perjudicial posible.";
            }
        } else if (isOdd) {
            nuance =
                "Número impar (" +
                finalRoll +
                "): El resultado tiene un matiz ('" +
                answer +
                ", pero...'). Modifica la situación sin anular el resultado.";
        }

        var promptAttached = null;
        if (isTwist) {
            promptAttached = this.generatePrompt();
        }

        return {
            pregunta: currentQuestion,
            respuesta: answer,
            tirada: finalRoll,
            detallesTirada: rollDetails,
            esGiro: isTwist,
            esCritico: isCritical,
            esImpar: isOdd,
            matiz: nuance,
            estimuloGiro: promptAttached
        };
    },

    generatePrompt: function () {
        var rV = this.d(100);
        var rN = this.d(100);
        var verb = this.promptsVerbs[rV - 1];
        var noun = this.promptsNouns[rN - 1];

        return {
            texto: verb + " + " + noun,
            verbo: verb,
            sustantivo: noun,
            rolls: "d100 (Verbo): [" + rV + "], d100 (Sustantivo): [" + rN + "]"
        };
    },

    generateDungeonName: function () {
        var r1 = this.d(50);
        var r2 = this.d(50);
        var r3 = this.d(50);

        var esName =
            this.dungeonNamesCol1_ES[r1 - 1] +
            " " +
            this.dungeonNamesCol2_ES[r2 - 1] +
            " de(l) " +
            this.dungeonNamesCol3_ES[r3 - 1];
        var enName =
            this.dungeonNamesCol1[r1 - 1] +
            " of the " +
            this.dungeonNamesCol2[r2 - 1] +
            " " +
            this.dungeonNamesCol3[r3 - 1];

        return {
            nombre: esName,
            nombreIngles: enName,
            rolls: "d50:[" + r1 + "], d50:[" + r2 + "], d50:[" + r3 + "]"
        };
    }
